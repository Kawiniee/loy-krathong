test('decorating challenge starts and reveals on time and accepts reactions', async ({ page }) => {
  await page.goto('/')
  await add(page, 'เล่นสองคนบนเครื่องเดียว')
  await page.getByRole('textbox', { name: 'ชื่อผู้เล่นคนที่ 1' }).fill('กอ')
  await page.getByRole('textbox', { name: 'ชื่อผู้เล่นคนที่ 2' }).fill('ใบ')
  await add(page, 'เข้างานทั้งสองคน')
  await page.getByRole('button', { name: 'ซุ้มแข่งแต่งกระทง' }).click()
  await page.getByLabel('เวลาแข่งขัน').selectOption('120')
  await page.clock.install()
  await add(page, 'สุ่มโจทย์และเริ่ม')
  await expect(page.getByText(/^เริ่มใน/)).toBeVisible()
  await page.clock.fastForward(3200)
  await expect(page.getByText(/เหลือ 1[12][0-9] วินาที/)).toBeVisible()
  await add(page, 'ฐานต้นกล้วย')
  await add(page, 'สลับผู้เล่น')
  await add(page, 'ฐานดอกบัว')
  await page.clock.fastForward(120_000)
  await expect(page.getByText('เปิดผลงานทั้งสองใบ')).toBeVisible()
  await expect(page.locator('.challenge-results image')).toHaveCount(2)
  await add(page, 'สวยจัง')
  await expect(page.getByRole('button', { name: 'สวยจัง' })).toHaveAttribute('aria-pressed', 'true')
})
