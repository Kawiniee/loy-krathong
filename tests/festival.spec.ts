test('@multiplayer two independent browser sessions share objects, reconnect, conceal gifts and float', async ({ page, browser, baseURL }) => {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  const guestContext = await browser.newContext()
  const second = await guestContext.newPage()
  const realtimePages = new Set<Page>()
  if (process.env.LK_PRODUCTION_URL) {
    for (const player of [page, second]) player.on('websocket', socket => {
      if (!new URL(socket.url()).pathname.includes('/realtime/')) return
      socket.on('framereceived', frame => {
        if (frame.payload.toString().includes('postgres_changes') && frame.payload.toString().includes('lk_signal')) {
          realtimePages.add(player)
        }
      })
    })
  }
  try {
    await page.goto('/')
    await add(page, 'สร้างห้องส่วนตัว')
    await page.getByRole('textbox', { name: 'ชื่อของคุณ' }).fill('บัว')
    await page.locator('dialog form').getByRole('button', { name: 'สร้างห้อง', exact: true }).click()
    await expect(page.getByText('รอเพื่อนเข้าห้อง')).toBeVisible()
    await add(page, 'คัดลอกลิงก์เชิญ')
    await expect(page.getByText('คัดลอกแล้ว')).toBeVisible()
    const invite = await page.evaluate(() => navigator.clipboard.readText())
    expect(invite).toContain(`${baseURL}/?room=`)
    await second.goto(invite)
    await second.getByRole('textbox', { name: 'ชื่อของคุณ' }).fill('ดาว')
    await second.getByRole('dialog').getByRole('button', { name: 'เข้าห้องเพื่อน', exact: true }).click()
    await expect(page.getByText('ดาว', { exact: true })).toBeVisible()
    await Promise.all([add(page, 'ไปแต่งกระทง'), add(second, 'ไปแต่งกระทง')])
    await Promise.all([add(page, 'ช่วยกันแต่ง'), add(second, 'ช่วยกันแต่ง')])
    await add(second, 'ดอกไม้')
    await Promise.all([add(page, 'ฐานต้นกล้วย'), add(second, 'บัวม่วง')])
    await expect(pieces(page)).toHaveCount(2)
    await expect(pieces(second)).toHaveCount(2)
    if (process.env.LK_PRODUCTION_URL) {
      await expect.poll(() => realtimePages.size, { message: 'Both players receive Supabase Realtime updates' }).toBe(2)
    }
    await second.reload()
    await add(second, 'ช่วยกันแต่ง')
    await expect(pieces(second)).toHaveCount(2)
    await Promise.all([add(page, 'แต่งให้กัน'), add(second, 'แต่งให้กัน')])
    await add(page, 'ฐานใบตอง')
    await add(second, 'ฐานดอกบัว')
    await add(page, 'ของขวัญพร้อมแล้ว')
    await expect(second.getByRole('button', { name: 'ดูกระทงที่เพื่อนแต่งให้' })).toBeHidden()
    await add(second, 'ของขวัญพร้อมแล้ว')
    await add(page, 'ดูกระทงที่เพื่อนแต่งให้')
    await expect(pieces(page)).toHaveCount(1)
    await Promise.all([go(page, 'ท่าน้ำลอยกระทง'), go(second, 'ท่าน้ำลอยกระทง')])
    await Promise.all([page.getByLabel('เลือกกระทง').selectOption('shared'), second.getByLabel('เลือกกระทง').selectOption('gift1')])
    await add(page, 'พร้อมลอย')
    await add(second, 'พร้อมลอย')
    await expect(page.getByRole('status', { name: 'นับถอยหลัง' })).toBeVisible()
    await expect(second.getByRole('status', { name: 'นับถอยหลัง' })).toBeVisible()
    await expect(page.getByText('ลอยกระทงแล้ว')).toBeVisible()
    await expect(second.getByText('ลอยกระทงแล้ว')).toBeVisible()
    await expect(page.locator('.river-image > g image')).toHaveCount(3)
    await expect(second.locator('.river-image > g image')).toHaveCount(3)
  } finally { await guestContext.close() }
})

